// Every text column hippo.db holds, classed: vetted at the sink that binds it, a key refused when secret-shaped, or out with a reason from a closed list.
// An out id, enum, path or tag label names `by`: hippo, the operator, or the src function that bounds it; caller free text is never out.

/** The closed list of reasons a text column may hold caller input unredacted. */
export type OutReason = 'id' | 'hash' | 'enum' | 'number' | 'timestamp' | 'tag label' | 'path';

/** The reasons whose value could be caller text, so each must name where it comes from. */
export type SourcedReason = 'id' | 'enum' | 'tag label' | 'path';

/** Who bounds an out value: hippo makes it, the store's operator sets it, or a named src function checks it. */
export type OutSource = 'hippo' | 'operator' | (string & {});

export type ColumnClass =
  | { readonly vetted: string }
  | { readonly refused: string }
  | { readonly out: Exclude<OutReason, SourcedReason> }
  | { readonly out: SourcedReason; readonly by: OutSource };

const id = { out: 'id', by: 'hippo' } as const;
const hash = { out: 'hash' } as const;
const enumeration = { out: 'enum', by: 'hippo' } as const;
const num = { out: 'number' } as const;
const at = { out: 'timestamp' } as const;
const vetted = (writer: string): ColumnClass => ({ vetted: writer });
/** A key a caller later looks up by value: its entrance or insert-only sink refuses a secret-shaped one. */
const refused = (writer: string): ColumnClass => ({ refused: writer });
const idBy = (by: OutSource): ColumnClass => ({ out: 'id', by });
const enumBy = (by: OutSource): ColumnClass => ({ out: 'enum', by });
const pathBy = (by: OutSource): ColumnClass => ({ out: 'path', by });
const tagBy = (by: OutSource): ColumnClass => ({ out: 'tag label', by });
/** A tenant comes from an api key row insertApiKey refused, a resolver sanitiseResolved bounds, or HIPPO_TENANT. */
const tenant = idBy('tenantOfApiKey');
/** An actor is hippo's own name, `api_key:<id>`, or a resolver subject sanitiseResolved refuses when secret-shaped. */
const actor = idBy('sanitiseResolved');
/** A project name is normalizeRemote's credential-free remote, a folder name, or one assertCallerProject refuses. */
const project = pathBy('assertCallerProject');
/** A key owner subject is set by insertApiKey, which refuses a secret-shaped one. */
const ownerSubject = idBy('insertApiKey');


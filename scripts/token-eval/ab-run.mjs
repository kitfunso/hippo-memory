#!/usr/bin/env node
/**
 * Paired agent A/B runner (ROADMAP Part IX, TE5). Runs real Claude Code
 * sessions on sequences of coding tasks with and without hippo, on the
 * machine where Claude Code is installed and signed in, and writes one
 * record per (task, arm, seed) for scripts/token-eval/ab-analyze.mjs.
 *
 * Protocol: docs/evals/2026-09-23-te5-token-ab-preregistration.md.
 *
 * What it does for each sequence x arm x seed:
 *   1. makes a fresh workspace holding the repository's history only up to
 *      the current task's base commit (never the fix, so neither the agent
 *      nor hippo's git learning can read the answer from `git log`);
 *   2. gives the arm its memory setup:
 *      no-memory     no hooks, an empty isolated hippo home
 *      hippo         hippo's own Claude Code hooks (generated by
 *                    `installJsonHooks`, exactly what `hippo hook install
 *                    claude-code` writes) and a fresh project store that
 *                    only this sequence's earlier tasks fill
 *      random-text   a hook injecting random repository lines, about as many
 *                    tokens per prompt as the hippo arm sent
 *      stale-memory  hippo's hooks over the finished hippo store of a
 *                    different sequence (another repository)
 *   3. for each task in order: resets the checkout to the task's baseRef,
 *      runs setup, runs `claude -p` headless, then checks out the task's
 *      hidden test files from fixRef and runs its test command. Exit 0 is
 *      resolved.
 *   4. records Claude Code's own usage for the run (modelUsage from the JSON
 *      result: the API's input, cache write, cache read and output tokens,
 *      and total_cost_usd at list price), plus turns, file reads, tool calls
 *      and repeated errors read from the session transcript, and what hippo
 *      sent (its token ledger, joined by session id).
 *
 * Isolation: every run uses `--setting-sources project` (your own
 * ~/.claude/settings.json hooks, hippo's included, do not load),
 * `--strict-mcp-config` (none of your MCP servers), its own HIPPO_HOME, and a
 * `hippo` on PATH that runs this checkout's bin/hippo.js. hippo's optional
 * LLM extraction is switched off so the arm has no spend outside Claude
 * Code's usage. Runs use `--permission-mode bypassPermissions` by default
 * inside the throwaway clones (Claude Code refuses it as root; pass
 * `--permission-mode acceptEdits` there, which allows edits but not shell
 * commands). Do not point it at a repository you care about.
 *
 * Tasks file (JSON):
 *   { "sequences": [ { "id", "cluster", "repo" (URL or local path),
 *       "tasks": [ { "id", "baseRef", "fixRef", "prompt",
 *                    "testFiles": [...], "test": "cmd", "setup"?: "cmd" } ] } ] }
 * The first task of each sequence is run but not scored (nothing to recall
 * yet); records carry `scored: false` for it.
 *
 * Run:
 *   npm run build
 *   node scripts/token-eval/ab-run.mjs --tasks tasks.json --out eval-runs/ \
 *     --model <model id> --seeds 3 --arms no-memory,hippo,random-text,stale-memory \
 *     [--max-budget-usd 3] [--dry-run]
 *   node scripts/token-eval/ab-analyze.mjs --runs eval-runs/runs.jsonl --prices prices.json
 */
import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';
import { execFileSync, spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, '..', '..');
const HIPPO_JS = path.join(REPO, 'bin', 'hippo.js');

export const ARMS = ['no-memory', 'hippo', 'random-text', 'stale-memory'];

// Loading or validating a tasks file never needs dist/; only a real run does.
let hippo = null;
async function loadHippo() {
  if (hippo) return hippo;
  try {
    const [{ installJsonHooks }, { openHippoDb, closeHippoDb }, { tokensBySession }, { loadAllEntries, isInitialized }] = await Promise.all([
      import('../../dist/hooks.js'),
      import('../../dist/db.js'),
      import('../../dist/token-ledger.js'),
      import('../../dist/store.js'),
    ]);
    hippo = { installJsonHooks, openHippoDb, closeHippoDb, tokensBySession, loadAllEntries, isInitialized };
  } catch (err) {
    throw new Error(`run npm run build first (ab-run needs dist/): ${err.message}`);
  }
  return hippo;
}

// Environment a child Claude Code session must not inherit: a parent
// session id makes the child report and log under the parent's id.
const STRIP_ENV = ['CLAUDE_CODE_SESSION_ID', 'CLAUDE_CODE_CHILD_SESSION', 'CLAUDE_CODE_REMOTE_SESSION_ID', 'HIPPO_SESSION_ID', 'HIPPO_HOME', 'HIPPO_TENANT'];

function sh(cmd, cwd, env, timeoutMs = 30 * 60_000, input = undefined) {
  const r = spawnSync(cmd, { cwd, env, shell: true, encoding: 'utf8', timeout: timeoutMs, maxBuffer: 1 << 28, input });
  return { status: r.status ?? 1, stdout: r.stdout ?? '', stderr: r.stderr ?? '' };
}

function git(args, cwd) {
  return execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
}

/** Validate a tasks file. Throws on the first problem. */
export function validateTasks(spec) {
  if (!spec || !Array.isArray(spec.sequences) || spec.sequences.length === 0) throw new Error('tasks file needs a non-empty "sequences" array');
  const ids = new Set();
  for (const s of spec.sequences) {
    for (const f of ['id', 'cluster', 'repo']) if (!s[f]) throw new Error(`sequence missing "${f}"`);
    if (ids.has(s.id)) throw new Error(`duplicate sequence id ${s.id}`);
    ids.add(s.id);
    if (!Array.isArray(s.tasks) || s.tasks.length < 2) throw new Error(`sequence ${s.id} needs at least 2 tasks (the first is not scored)`);
    for (const t of s.tasks) {
      for (const f of ['id', 'baseRef', 'fixRef', 'prompt', 'test']) if (!t[f]) throw new Error(`task in ${s.id} missing "${f}"`);
      if (!Array.isArray(t.testFiles)) throw new Error(`task ${t.id} needs a "testFiles" array`);
      if (t.needsReview) throw new Error(`task ${t.id} still has needsReview: rewrite its prompt as the problem (not the fix), then delete needsReview`);
    }
  }
  return spec;
}

/** A `hippo` on PATH that runs this checkout, for hook commands. */
function writeHippoShim(binDir) {
  fs.mkdirSync(binDir, { recursive: true });
  fs.writeFileSync(path.join(binDir, 'hippo'), `#!/bin/sh\nexec "${process.execPath}" "${HIPPO_JS}" "$@"\n`, { mode: 0o755 });
  fs.writeFileSync(path.join(binDir, 'hippo.cmd'), `@"${process.execPath}" "${HIPPO_JS}" %*\r\n`);
}

/** The settings hippo's installer writes for Claude Code, generated under a throwaway HOME. */
function hippoHookSettings(tmpHome) {
  const saved = { HOME: process.env.HOME, USERPROFILE: process.env.USERPROFILE };
  process.env.HOME = tmpHome;
  process.env.USERPROFILE = tmpHome;
  try {
    hippo.installJsonHooks('claude-code');
    return JSON.parse(fs.readFileSync(path.join(tmpHome, '.claude', 'settings.json'), 'utf8'));
  } finally {
    for (const [k, v] of Object.entries(saved)) {
      if (v === undefined) delete process.env[k];
      else process.env[k] = v;
    }
  }
}

function randomTextSettings(tokens) {
  const hook = path.join(HERE, 'random-text-hook.mjs');
  return { hooks: { UserPromptSubmit: [{ hooks: [{ type: 'command', command: `"${process.execPath}" "${hook}" --tokens ${Math.max(1, Math.round(tokens))}`, timeout: 10 }] }] } };
}

function findTranscript(projectsDir, sessionId) {
  if (!sessionId || !fs.existsSync(projectsDir)) return null;
  for (const p of fs.readdirSync(projectsDir)) {
    const f = path.join(projectsDir, p, `${sessionId}.jsonl`);
    if (fs.existsSync(f)) return f;
  }
  return null;
}

/**
 * Work metrics from a transcript: tool calls, file reads (Read tool calls),
 * and error results whose signature was already seen earlier in the
 * sequence (`seenErrors` is updated).
 */
export function transcriptWork(file, seenErrors) {
  const work = { toolCalls: 0, fileReads: 0, repeatedErrors: 0 };
  if (!file) return null;
  const seenTools = new Set();
  for (const line of fs.readFileSync(file, 'utf8').split('\n')) {
    if (!line.trim()) continue;
    let o;
    try {
      o = JSON.parse(line);
    } catch {
      continue;
    }
    const content = o.message && Array.isArray(o.message.content) ? o.message.content : [];
    for (const block of content) {
      if (block.type === 'tool_use' && !seenTools.has(block.id)) {
        seenTools.add(block.id);
        work.toolCalls++;
        if (block.name === 'Read') work.fileReads++;
      } else if (block.type === 'tool_result' && block.is_error) {
        const text = Array.isArray(block.content) ? block.content.map((c) => c.text ?? '').join(' ') : String(block.content ?? '');
        const sig = text.replace(/\d+/g, '#').replace(/\s+/g, ' ').trim().slice(0, 160);
        if (!sig) continue;
        if (seenErrors.has(sig)) work.repeatedErrors++;
        else seenErrors.add(sig);
      }
    }
  }
  return work;
}

/**
 * Sum Claude Code's per-model usage from a `--output-format json` result.
 * `modelUsage` is the billing aggregate (its costUSD values sum to
 * total_cost_usd); the top-level `usage` can read zero when a run stops on
 * its budget cap, so it is only a fallback.
 */
export function usageFromResult(result) {
  const usage = { inputTokens: 0, cacheWriteTokens: 0, cacheReadTokens: 0, outputTokens: 0 };
  const models = result.modelUsage ?? {};
  for (const m of Object.values(models)) {
    usage.inputTokens += Number(m.inputTokens) || 0;
    usage.cacheWriteTokens += Number(m.cacheCreationInputTokens) || 0;
    usage.cacheReadTokens += Number(m.cacheReadInputTokens) || 0;
    usage.outputTokens += Number(m.outputTokens) || 0;
  }
  if (Object.keys(models).length === 0 && result.usage) {
    usage.inputTokens = Number(result.usage.input_tokens) || 0;
    usage.cacheWriteTokens = Number(result.usage.cache_creation_input_tokens) || 0;
    usage.cacheReadTokens = Number(result.usage.cache_read_input_tokens) || 0;
    usage.outputTokens = Number(result.usage.output_tokens) || 0;
  }
  return usage;
}

/**
 * Move the workspace to a task's base commit without its future: the cache
 * clone gets a ref at baseRef and the workspace fetches only that ref, so
 * the fix commit (and anything after the base) is not in the workspace's
 * history for the agent, or hippo's git learning, to find.
 */
function checkoutBase(cacheDir, workDir, sequenceId, t) {
  const ref = `refs/eval/${sequenceId}/${t.id}`;
  git(['update-ref', ref, t.baseRef], cacheDir);
  git(['fetch', '--quiet', '--no-tags', cacheDir, `+${ref}:refs/remotes/eval/base`], workDir);
  git(['checkout', '--quiet', '-f', '--detach', 'refs/remotes/eval/base'], workDir);
  git(['clean', '-fdq', '-e', '.hippo'], workDir);
}

/** Write the task's hidden test files from fixRef, read from the cache clone. */
function writeHiddenTests(cacheDir, workDir, t) {
  for (const f of t.testFiles) {
    const content = execFileSync('git', ['show', `${t.fixRef}:${f}`], { cwd: cacheDir, maxBuffer: 1 << 28 });
    fs.mkdirSync(path.dirname(path.join(workDir, f)), { recursive: true });
    fs.writeFileSync(path.join(workDir, f), content);
  }
}

/** Added lines of a task's gold diff that are long enough to be a leak signal. */
function goldLines(cacheDir, t) {
  try {
    return git(['diff', t.baseRef, t.fixRef], cacheDir)
      .split('\n')
      .filter((l) => l.startsWith('+') && !l.startsWith('+++'))
      .map((l) => l.slice(1).trim())
      .filter((l) => l.length >= 40);
  } catch {
    return [];
  }
}

function storeLeaks(hippoRoot, lines) {
  if (!hippo.isInitialized(hippoRoot) || lines.length === 0) return false;
  const text = hippo.loadAllEntries(hippoRoot).map((e) => e.content).join('\n');
  return lines.some((l) => text.includes(l));
}

function hippoSentFor(hippoRoot, sessionId) {
  if (!sessionId || !hippo.isInitialized(hippoRoot)) return null;
  const db = hippo.openHippoDb(hippoRoot);
  try {
    const row = hippo.tokensBySession(db, 'default', '1970-01-01T00:00:00.000Z').find((r) => r.sessionId === sessionId);
    return row ?? { sessionId, sent: 0, skipped: 0, injections: 0 };
  } catch {
    return null;
  } finally {
    hippo.closeHippoDb(db);
  }
}

/** Donor store for stale-memory: another cluster in this run, else a --donor-runs record still on disk. */
export function findDonor(spec, s, seed, hippoStores, donorRuns) {
  const donors = spec.sequences.filter((x) => x.id !== s.id && x.cluster !== s.cluster);
  const inRun = donors.map((x) => hippoStores.get(`${x.id}|${seed}`)).find(Boolean);
  if (inRun) return inRun;
  if (!donorRuns) return null;
  const runsFile = path.join(donorRuns, 'runs.jsonl');
  if (!fs.existsSync(runsFile)) return null;
  for (const line of fs.readFileSync(runsFile, 'utf8').split('\n')) {
    if (!line.trim()) continue;
    let r;
    try {
      r = JSON.parse(line);
    } catch {
      continue;
    }
    if (r.arm !== 'hippo' || r.seed !== seed || r.cluster === s.cluster) continue;
    const dir = path.join(donorRuns, 'work', r.sequence, 'hippo', `seed${seed}`, '.hippo');
    if (fs.existsSync(dir)) return dir;
  }
  return null;
}

/** Preflight so stale-memory fails before any session, not midway through a run. */
export function checkDonors(spec, arms, seeds, donorRuns) {
  if (!arms.includes('stale-memory')) return;
  for (const s of spec.sequences) {
    const anotherClusterInFile = spec.sequences.some((x) => x.id !== s.id && x.cluster !== s.cluster);
    if (anotherClusterInFile && arms.includes('hippo')) continue;
    for (let seed = 1; seed <= seeds; seed++) {
      if (!findDonor(spec, s, seed, new Map(), donorRuns)) {
        throw new Error(`stale-memory for ${s.id} seed ${seed} needs a donor: another cluster with hippo in arms, or --donor-runs pointing at a finished hippo run of another cluster`);
      }
    }
  }
}

/**
 * Plan every run, in the order they must execute. random-text and
 * stale-memory need the hippo arm's results for the same seed, so they come
 * after it. hippo and no-memory swap order between seeds (odd seeds run
 * hippo first) so neither arm always gets the warmer prompt cache.
 */
export function planRuns(spec, arms, seeds) {
  const plan = [];
  for (let seed = 1; seed <= seeds; seed++) {
    const pair = seed % 2 === 1 ? ['hippo', 'no-memory'] : ['no-memory', 'hippo'];
    const ordered = [...pair, 'random-text', 'stale-memory'].filter((a) => arms.includes(a));
    for (const arm of ordered) {
      for (const s of spec.sequences) plan.push({ arm, seed, sequence: s });
    }
  }
  return plan;
}

/** Run the whole plan. Returns the records written. */
export async function runAll(opts) {
  await loadHippo();
  const { spec, arms, seeds, outDir, model, claudeBin = 'claude', maxBudgetUsd = null, projectsDir, settleMs = 5000, warmup = true, permissionMode = 'bypassPermissions', donorRuns = null, log = console.log } = opts;
  fs.mkdirSync(outDir, { recursive: true });
  const runsFile = path.join(outDir, 'runs.jsonl');
  const binDir = path.join(outDir, 'bin');
  writeHippoShim(binDir);
  const cacheDir = path.join(outDir, 'repo-cache');
  const records = [];
  const hippoStores = new Map(); // `${sequenceId}|${seed}` -> finished hippo store
  const hippoMeanTokens = new Map(); // `${sequenceId}|${seed}` -> mean tokens per injection
  let claudeVersion = null;
  try {
    claudeVersion = sh(`${claudeBin} --version`, outDir, process.env).stdout.trim() || null;
  } catch {
    claudeVersion = null;
  }
  if (warmup) {
    // One unrecorded call so the first recorded run does not alone pay the
    // cold prompt-cache write for Claude Code's system prompt and tools.
    const warmDir = path.join(outDir, 'warmup');
    fs.mkdirSync(warmDir, { recursive: true });
    const warmEnv = { ...process.env };
    for (const k of STRIP_ENV) delete warmEnv[k];
    const warmArgs = ['-p', '--output-format', 'json', '--setting-sources', 'project', '--strict-mcp-config'];
    if (model) warmArgs.push('--model', model);
    sh(`${claudeBin} ${warmArgs.join(' ')}`, warmDir, warmEnv, 10 * 60_000, 'Reply with the single word OK.');
  }

  for (const run of planRuns(spec, arms, seeds)) {
    const { arm, seed, sequence: s } = run;
    const key = `${s.id}|${seed}`;
    const cached = path.join(cacheDir, s.id);
    if (!fs.existsSync(cached)) {
      fs.mkdirSync(cacheDir, { recursive: true });
      execFileSync('git', ['clone', '--quiet', s.repo, cached], { stdio: 'ignore' });
    }
    const workDir = path.join(outDir, 'work', s.id, arm, `seed${seed}`);
    fs.rmSync(workDir, { recursive: true, force: true });
    fs.mkdirSync(path.dirname(workDir), { recursive: true });
    fs.mkdirSync(workDir, { recursive: true });
    git(['init', '--quiet'], workDir);
    git(['config', 'user.email', 'eval@localhost'], workDir);
    git(['config', 'user.name', 'eval'], workDir);
    fs.appendFileSync(path.join(workDir, '.git', 'info', 'exclude'), '\n.hippo/\n');
    // History up to the first task's base only; hippo init below learns from it.
    checkoutBase(cached, workDir, s.id, s.tasks[0]);

    const hippoHome = path.join(outDir, 'hippo-home', s.id, arm, `seed${seed}`);
    fs.rmSync(hippoHome, { recursive: true, force: true });
    fs.mkdirSync(hippoHome, { recursive: true });
    const env = { ...process.env };
    for (const k of STRIP_ENV) delete env[k];
    env.HIPPO_HOME = hippoHome;
    env.EVAL_SEED = String(seed);
    env.PATH = `${binDir}${path.delimiter}${env.PATH ?? ''}`;

    const hippoRoot = path.join(workDir, '.hippo');
    let settings = {};
    if (arm === 'hippo' || arm === 'stale-memory') {
      settings = hippoHookSettings(path.join(outDir, 'hook-home'));
      if (arm === 'stale-memory') {
        const donor = findDonor(spec, s, seed, hippoStores, donorRuns);
        if (!donor) throw new Error(`stale-memory for ${s.id} seed ${seed} needs a donor: pass --donor-runs or run the hippo arm with at least two clusters`);
        fs.cpSync(donor, hippoRoot, { recursive: true });
      } else {
        sh(`"${process.execPath}" "${HIPPO_JS}" init`, workDir, env);
      }
      const cfgPath = path.join(hippoRoot, 'config.json');
      const cfg = fs.existsSync(cfgPath) ? JSON.parse(fs.readFileSync(cfgPath, 'utf8')) : {};
      fs.writeFileSync(cfgPath, JSON.stringify({ ...cfg, extraction: { enabled: false } }, null, 2));
    } else if (arm === 'random-text') {
      settings = randomTextSettings(hippoMeanTokens.get(key) ?? 300);
    }
    const settingsFile = path.join(outDir, 'settings', `${s.id}-${arm}-seed${seed}.json`);
    fs.mkdirSync(path.dirname(settingsFile), { recursive: true });
    fs.writeFileSync(settingsFile, JSON.stringify(settings, null, 2));

    const seenErrors = new Set();
    let hippoSentTotal = 0;
    let hippoInjections = 0;
    s.tasks.forEach((t, position) => {
      const startedAt = new Date().toISOString();
      checkoutBase(cached, workDir, s.id, t);
      const leak = (arm === 'hippo' || arm === 'stale-memory') ? storeLeaks(hippoRoot, goldLines(cached, t)) : false;
      const rawDir = path.join(outDir, 'raw', s.id, arm, `seed${seed}`);
      fs.mkdirSync(rawDir, { recursive: true });
      if (t.setup) {
        const setup = sh(t.setup, workDir, env);
        if (setup.status !== 0) {
          // No claude session, no hidden-test run: a failed setup is not a genuine "not resolved".
          fs.writeFileSync(path.join(rawDir, `${t.id}.setup.txt`), `${setup.stdout}\n${setup.stderr}`.slice(-20000));
          const record = {
            taskId: t.id, cluster: s.cluster, sequence: s.id, position, scored: position > 0, arm, seed,
            resolved: false, usage: null, costUsd: null, turns: null,
            sessionId: null, transcriptFound: false,
            agentError: `setup failed (exit ${setup.status})`,
            hippo: null, leak, invalid: 'setup', model: model ?? null, claudeVersion, startedAt,
          };
          records.push(record);
          fs.appendFileSync(runsFile, `${JSON.stringify(record)}\n`);
          log(`${s.id} ${t.id} ${arm} seed${seed}: setup failed (exit ${setup.status}), skipped`);
          return;
        }
      }
      // The prompt goes on stdin: long prompts break command-line quoting,
      // especially under Windows cmd.
      const args = ['-p', '--output-format', 'json', '--setting-sources', 'project',
        '--settings', JSON.stringify(settingsFile), '--strict-mcp-config', '--permission-mode', permissionMode];
      if (model) args.push('--model', model);
      if (maxBudgetUsd) args.push('--max-budget-usd', String(maxBudgetUsd));
      const cc = sh(`${claudeBin} ${args.join(' ')}`, workDir, env, 60 * 60_000, t.prompt);
      let result = null;
      try {
        result = JSON.parse(cc.stdout.trim().split('\n').filter(Boolean).pop() ?? '');
      } catch {
        result = null;
      }
      fs.writeFileSync(path.join(rawDir, `${t.id}.json`), cc.stdout || JSON.stringify({ error: cc.stderr.slice(0, 4000), status: cc.status }));
      if ((arm === 'hippo' || arm === 'stale-memory') && settleMs > 0) {
        // SessionEnd runs capture and sleep in a background worker; let it finish.
        Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, settleMs);
      }

      writeHiddenTests(cached, workDir, t);
      const test = sh(t.test, workDir, env);
      fs.writeFileSync(path.join(rawDir, `${t.id}.test.txt`), `${test.stdout}\n${test.stderr}`.slice(-20000));

      const sessionId = result?.session_id ?? null;
      const transcript = findTranscript(projectsDir, sessionId);
      const work = transcriptWork(transcript, seenErrors);
      const hippo = (arm === 'hippo' || arm === 'stale-memory') ? hippoSentFor(hippoRoot, sessionId) : null;
      if (hippo) {
        hippoSentTotal += hippo.sent;
        hippoInjections += hippo.injections;
      }
      const record = {
        taskId: t.id,
        cluster: s.cluster,
        sequence: s.id,
        position,
        scored: position > 0,
        arm,
        seed,
        resolved: result !== null && test.status === 0,
        usage: result ? usageFromResult(result) : null,
        costUsd: result?.total_cost_usd ?? null,
        turns: result?.num_turns ?? null,
        ...work,
        sessionId,
        transcriptFound: transcript !== null,
        agentError: result === null ? `claude exited ${cc.status}: ${cc.stderr.slice(0, 300)}` : (result.is_error ? result.subtype ?? 'error' : null),
        hippo,
        leak,
        invalid: result === null ? 'no-result' : (leak ? 'leak' : null),
        model: model ?? null,
        claudeVersion,
        startedAt,
      };
      records.push(record);
      fs.appendFileSync(runsFile, `${JSON.stringify(record)}\n`);
      log(`${s.id} ${t.id} ${arm} seed${seed}: ${record.resolved ? 'resolved' : 'not resolved'}${record.costUsd !== null ? `, $${record.costUsd.toFixed(4)}` : ''}${record.invalid ? ` (invalid: ${record.invalid})` : ''}`);
    });
    if (arm === 'hippo') {
      hippoStores.set(key, hippoRoot);
      if (hippoInjections > 0) hippoMeanTokens.set(key, hippoSentTotal / hippoInjections);
    }
  }
  return records;
}

async function main() {
  const argv = process.argv;
  const flag = (name, fallback) => {
    const i = argv.indexOf(name);
    return i >= 0 && i + 1 < argv.length ? argv[i + 1] : fallback;
  };
  const tasksFile = flag('--tasks', null);
  const outDir = flag('--out', null);
  if (!tasksFile || !outDir) {
    console.error('Usage: node scripts/token-eval/ab-run.mjs --tasks tasks.json --out DIR --model MODEL [--seeds 3] [--arms no-memory,hippo,random-text,stale-memory] [--max-budget-usd N] [--donor-runs DIR] [--dry-run]');
    process.exit(1);
  }
  const spec = validateTasks(JSON.parse(fs.readFileSync(tasksFile, 'utf8')));
  const arms = flag('--arms', 'no-memory,hippo,random-text,stale-memory').split(',').map((a) => a.trim());
  for (const a of arms) if (!ARMS.includes(a)) throw new Error(`unknown arm ${a}; known: ${ARMS.join(', ')}`);
  const seeds = Number(flag('--seeds', '3'));
  const donorRunsArg = flag('--donor-runs', null);
  const donorRuns = donorRunsArg ? path.resolve(donorRunsArg) : null;
  checkDonors(spec, arms, seeds, donorRuns);
  const plan = planRuns(spec, arms, seeds);
  const taskRuns = plan.reduce((n, r) => n + r.sequence.tasks.length, 0);
  console.log(`${plan.length} sequence runs, ${taskRuns} Claude Code sessions (${arms.join(', ')}; ${seeds} seeds).`);
  if (argv.includes('--dry-run')) {
    for (const r of plan) console.log(`  ${r.arm} seed${r.seed} ${r.sequence.id}: ${r.sequence.tasks.map((t) => t.id).join(', ')}`);
    return;
  }
  await runAll({
    spec,
    arms,
    seeds,
    outDir: path.resolve(outDir),
    model: flag('--model', null),
    claudeBin: flag('--claude-bin', 'claude'),
    maxBudgetUsd: flag('--max-budget-usd', null),
    projectsDir: flag('--projects', path.join(os.homedir(), '.claude', 'projects')),
    settleMs: Number(flag('--settle-ms', '5000')),
    warmup: !argv.includes('--no-warmup'),
    permissionMode: flag('--permission-mode', 'bypassPermissions'),
    donorRuns,
  });
  console.log(`\nRecords: ${path.join(path.resolve(outDir), 'runs.jsonl')}\nAnalyze: node scripts/token-eval/ab-analyze.mjs --runs ${path.join(outDir, 'runs.jsonl')} --prices prices.json`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((err) => {
    console.error(err.message);
    process.exit(1);
  });
}
